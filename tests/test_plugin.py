def test_the_claude_skill_carries_the_version_clawhub_requires():
    """ClawHub refuses a skill whose frontmatter lacks a semver `version`, and requires `name` to
    match the parent directory. Claude Code ignores the extra key, which is the whole reason one
    generated file can serve both — but only for as long as the stamp keeps happening, and a release
    bump is exactly when it would quietly stop."""
    fm = frontmatter(CLAUDE_SKILL)
    assert fm["name"] == "treg" == CLAUDE_SKILL.parent.name
    assert fm["version"] == package_version()
    assert fm.get("description"), "the description is what drives discovery in every registry"


def test_the_claude_plugin_declares_no_connector_in_its_manifest():
    """Skills-only is a property of the MANIFEST, not of the end state — the skill still wires up the
    MCP tools at first run (see the ordering test below). The distinction is the whole design.

    Anything declared here is registered at INSTALL time, before any human has signed in, so a
    declared MCP server means five always-on tools that 401 on every call. Leaving it out is what
    makes `/plugin install` a zero-config action and keeps this off the connector-review track."""
    manifest = json.loads(CLAUDE_MANIFEST.read_text(encoding="utf-8"))
    assert "mcpServers" not in manifest
    assert not (ROOT / ".mcp.json").exists(), "a root .mcp.json would be picked up by the plugin"


def test_the_claude_bootstrap_sets_up_cli_login_and_mcp_in_order():
    """The plugin is skills-only at the MANIFEST level so it installs with no token and no config —
    but the intended first run ends with the CLI, the skill AND the MCP tools all in place. The skill
    is what wires the last two up, because only it runs after the human is present to sign in.

    Order is load-bearing and not merely stylistic: `cmd_mcp_install` (cli.py) reads the token from
    config and `sys.exit`s before writing anything when there is none. Run `treg mcp install` ahead
    of `treg login` and it does nothing at all — silently enough that an agent would move on assuming
    the tools exist."""
    text = CLAUDE_SKILL.read_text(encoding="utf-8")
    head = text.split("---", 3)[2]          # the prepended bootstrap, before the skill's own body
    steps = ["install.sh", "treg login", "treg mcp install"]
    positions = [head.find(s) for s in steps]
    assert all(p != -1 for p in positions), f"the bootstrap is missing one of {steps}"
    assert positions == sorted(positions), (
        "the bootstrap must present install -> login -> mcp install IN THAT ORDER; "
        "`treg mcp install` exits without writing if it runs before there is a token")
    assert "restart" in head.lower(), (
        "registering an MCP server needs an agent restart to take effect — an agent that does not "
        "say so leaves the human waiting for tools that will not appear this session")


def test_the_marketplace_resolves_to_a_real_plugin():
    """`source` is resolved by Claude Code on the user's machine, not here. A source that points at
    a directory with no `skills/` installs an empty plugin — silently, which is the failure mode
    CLAUDE.md warns about for exactly this kind of markup."""
    market = json.loads(CLAUDE_MARKETPLACE.read_text(encoding="utf-8"))
    manifest = json.loads(CLAUDE_MANIFEST.read_text(encoding="utf-8"))
    assert len(market["plugins"]) == 1
    entry = market["plugins"][0]
    assert entry["name"] == manifest["name"]
    root = (CLAUDE_PLUGIN.parent / entry["source"]).resolve()
    assert (root / "skills" / "treg" / "SKILL.md").exists(), (
        f"marketplace source {entry['source']!r} resolves to {root}, which ships no treg skill")
    # `source: "./"` makes the plugin root the REPO root, so anything Claude Code auto-discovers
    # there ships to users. Only `skills/` is intended.
    for stray in ("commands", "agents", "hooks"):
        assert not (root / stray).is_dir(), (
            f"a root `{stray}/` directory would be published as part of the plugin")


def test_one_product_one_sentence():
    """The positioning is hand-maintained across two stores, and two listings describing the same
    product differently is drift nobody notices until a user reads both."""
    claude = json.loads(CLAUDE_MANIFEST.read_text(encoding="utf-8"))
    market = json.loads(CLAUDE_MARKETPLACE.read_text(encoding="utf-8"))
    assert claude["description"] == POSITIONING
    assert market["description"] == POSITIONING


def test_the_codex_subtitle_fits_the_field():
    """Codex renders `shortDescription` as the listing SUBTITLE, and the upload form rejects
    anything over 30 characters — so it cannot carry the full positioning sentence the way the
    Claude manifest's `description` does. It keeps the front half, which is the half that
    identifies the product."""
    subtitle = json.loads(MANIFEST.read_text(encoding="utf-8"))["interface"]["shortDescription"]
    assert len(subtitle) <= 30, f"subtitle is {len(subtitle)} chars, the field allows 30"
    assert subtitle.split()[0] in POSITIONING


def test_the_listings_agree_on_the_licence():
    """`LICENSE` is Apache-2.0 plus a hosted-service restriction. The Codex manifest claimed MIT for
    a while, which is a licence the project has never been under — and a store listing is where a
    wrong licence does actual damage."""
    for path in ALL_MANIFESTS.values():
        manifest = json.loads(path.read_text(encoding="utf-8"))
        assert manifest["license"] == "Apache-2.0", f"{path.name} misstates the licence"


def test_the_cursor_layout_matches_cursors_template():
    """Cursor prescribes the shape (github.com/cursor/plugin-template): marketplace manifest at the
    repo root, plugin under plugins/<name>/ with its own .cursor-plugin/plugin.json, and `source`
    the relative path to that folder. Unlike Claude Code, the plugin root is never the repo root —
    get that wrong and the listing installs nothing. Their own validator agrees with this test."""
    market = json.loads(CURSOR_MARKETPLACE.read_text(encoding="utf-8"))
    manifest = json.loads(CURSOR_MANIFEST.read_text(encoding="utf-8"))

    assert len(market["plugins"]) == 1
    entry = market["plugins"][0]
    assert entry["name"] == manifest["name"] == "treg"
    assert entry["name"] == entry["name"].lower() and " " not in entry["name"]  # kebab-case
    assert entry["source"] == f"./plugins/{entry['name']}", (
        "`source` must be the relative path to the plugin folder, and match the folder name")

    root = (ROOT / entry["source"]).resolve()
    assert root == CURSOR_PLUGIN_DIR.resolve()
    assert (root / ".cursor-plugin" / "plugin.json").exists()
    assert (root / "skills" / "treg" / "SKILL.md").exists()

    # Cursor's marketplace schema differs from Claude's: a metadata{} block rather than a top-level
    # description, and no $schema. Do not "fix" one to look like the other.
    assert market["metadata"]["description"] and market["metadata"]["version"]
    assert "description" not in market

    logo = manifest["logo"]
    assert not logo.startswith("./"), "the template writes `assets/logo.svg`, not `./assets/...`"
    assert (root / logo).exists(), f"plugin.json points at {logo}, which does not exist"


